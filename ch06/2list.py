# 建立一個二維陣列
lst = [[4,8,5,9],[13,16,19,15],[28,25,29,24]]
print(lst)      # 印出 [[4,8,5,9],[13,16,19,15],[28,25,29,24]]
# 取得串列第一維的大小
n1 = len(lst)   # n1 ← 3
print(n1)        # 印出 3
# 取出第 2 個 row 的資料 
print(lst[0])   # 印出 [4, 8, 5, 9]
print(lst[1])   # 印出 [13, 16, 19, 15]
print(lst[2])   # 印出 [28, 25, 29, 24]
# 取得串列第二維的大小，該 row 有 lst[1][0],lst[1][1],lst[1][2],lst[1][3]  三個元素
n2 = len(lst[1]) # n2 ← 4
print(lst[1][2]) # 印出 19